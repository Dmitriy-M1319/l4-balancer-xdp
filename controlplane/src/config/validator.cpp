#include "validator.h"

using namespace blncr::validators;

const std::regex IPValidator::IPv4_REGEX(
    "^((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\\.){3}"
    "(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)$"
);

const std::regex IPValidator::IPv6_REGEX(
    "^("
    "([0-9a-fA-F]{1,4}:){7}[0-9a-fA-F]{1,4}|"              // 1:2:3:4:5:6:7:8
    "([0-9a-fA-F]{1,4}:){1,7}:|"                            // 1::, 1:2:3:4:5:6:7::
    "([0-9a-fA-F]{1,4}:){1,6}:[0-9a-fA-F]{1,4}|"            // 1::8, 1:2:3:4:5:6::8
    "([0-9a-fA-F]{1,4}:){1,5}(:[0-9a-fA-F]{1,4}){1,2}|"     // 1::7:8, 1:2:3:4:5::7:8
    "([0-9a-fA-F]{1,4}:){1,4}(:[0-9a-fA-F]{1,4}){1,3}|"     // 1::6:7:8, 1:2:3:4::6:7:8
    "([0-9a-fA-F]{1,4}:){1,3}(:[0-9a-fA-F]{1,4}){1,4}|"     // 1::5:6:7:8, 1:2:3::5:6:7:8
    "([0-9a-fA-F]{1,4}:){1,2}(:[0-9a-fA-F]{1,4}){1,5}|"     // 1::4:5:6:7:8, 1:2::4:5:6:7:8
    "[0-9a-fA-F]{1,4}:((:[0-9a-fA-F]{1,4}){1,6})|"          // 1::3:4:5:6:7:8, ::2:3:4:5:6:7:8
    ":((:[0-9a-fA-F]{1,4}){1,7}|:)|"                         // ::2:3:4:5:6:7:8, ::8, :: 
    
    "fe80:(:[0-9a-fA-F]{0,4}){0,4}%[0-9a-zA-Z]{1,}|"        // link-local IPv6
    "::(ffff(:0{1,4}){0,1}:){0,1}"
    "((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\\.){3,3}"
    "(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)|"                // IPv4-mapped IPv6
    "([0-9a-fA-F]{1,4}:){1,4}:"
    "((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\\.){3,3}"
    "(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)"                 // IPv4-embedded IPv6
    ")$"
);

